/** Deterministic description of how a track is *rendered* by the synth engine. */
export interface TrackSpec {
  /** Musical key root, MIDI note number (36 = C2). */
  root: number;
  /** Scale degrees used for melodic material (semitones from root). */
  scale: number[];
  /** Chord progression as scale-degree triads, one entry per bar. */
  progression: number[];
  bpm: number;
  bars: number;
  /** Which voices are active. */
  voices: {
    pad: boolean;
    bass: boolean;
    arp: boolean;
    drums: boolean;
    pluck: boolean;
    shimmer: boolean;
    /** Filmi additions (optional so older specs stay valid). */
    tabla?: boolean;
    sitar?: boolean;
    flute?: boolean;
    strings?: boolean;
  };
  /** 0..1 swing amount on the 16th grid. */
  swing: number;
  /** Overall gain trim. */
  gain: number;
  /** Deterministic seed for melodic material / noise. */
  seed: number;
}

