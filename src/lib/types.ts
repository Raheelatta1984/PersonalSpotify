export interface Track {
  id: string;
  title: string;
  /** Title in its own script (Devanagari for the Bollywood collection). */
  nativeTitle?: string;
  /** ISO-ish language tag of the original song, e.g. "hi". */
  language?: string;
  artistId: string;
  artist: string;
  album: string;
  year: number;
  genres: Genre[];
  moods: Mood[];
  tags: string[];
  bpm: number;
  musicalKey: string;
  energy: number;
  valence: number;
  instrumental: boolean;
  /** Track length in seconds (== rendered length). */
  duration: number;
  /** Human-readable blurb used by the AI search index. */
  description: string;
  /** Free-text "sounds like" references that the semantic index learns from. */
  soundsLike: string[];
  palette: [string, string];
  spec: TrackSpec;
  /** Pre-computed popularity 0..100, used as a ranking prior. */
  popularity: number;
  /**
   * Present when the track was imported from the open web instead of the
   * built-in synth catalog. Keeps the original song URL attached to the
   * playlist entry so "add to playlist" never loses where it came from.
   */
  web?: {
    id: string;
    sourceUrl: string;
    provider: string;
    providerLabel: string;
    playbackKind: PlaybackKind;
    license: string;
    artworkUrl?: string;
  };
}

