const DEFAULTS: TrackSpec["voices"] = {
  pad: true,
  bass: true,
  arp: false,
  drums: true,
  pluck: false,
  shimmer: false,
  tabla: false,
  sitar: false,
  flute: false,
  strings: false,
};

function buildSpec(seed: TrackSeed): TrackSpec {
  const durationBarTarget = seed.bars;
  return {
    root: seed.root,
    scale: [...SCALES[seed.scale]],
    progression: seed.progression,
    bpm: seed.bpm,
    bars: durationBarTarget,
    voices: { ...DEFAULTS, ...seed.voices },
    swing: seed.swing ?? 0,
    gain: 1.15,
    // Derive the melodic seed from the *id*, not from whatever digits happen to
    // be in it: ids without digits would otherwise all collapse onto seed 17
    // and drift toward each other's fingerprints.
    seed: (hashString(seed.id) % 900000) + 1000,
  };
}

function paletteFor(artistId: string): [string, string] {
  const artist = ARTISTS.find((a) => a.id === artistId);
  return artist ? artist.palette : ["#59d4b5", "#123f3a"];
}

export const TRACKS: Track[] = TRACK_SEEDS.map((seed) => {
  const artist = ARTISTS.find((a) => a.id === seed.artistId)!;
  const spec = buildSpec(seed);
  const duration = Math.round((spec.bars * 4 * 60) / spec.bpm);
  const names: Record<number, string> = { 36: "C2", 37: "C#2", 38: "D2", 39: "D#2", 40: "E2", 41: "F2", 42: "F#2", 43: "G2", 44: "G#2", 45: "A2", 46: "A#2", 47: "B2" };
  return {
    id: seed.id,
    title: seed.title,
    nativeTitle: seed.nativeTitle,
    language: seed.language,
    artistId: seed.artistId,
    artist: artist.name,
    album: seed.album,
    year: seed.year,
    genres: seed.genres,
    moods: seed.moods,
    tags: seed.tags,
    bpm: seed.bpm,
    musicalKey: `${names[seed.root] ?? "A2"} ${seed.scale}`,
    energy: seed.energy,
    valence: seed.valence,
    instrumental: seed.instrumental,
    duration,
    description: seed.description,
    soundsLike: seed.soundsLike,
    palette: paletteFor(seed.artistId),
    spec,
    popularity: seed.popularity,
  };
});

